#!/usr/bin/env python3
import sys
import math
import argparse
try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    print("Error: Pillow library is required. Install it using 'pip install Pillow'")
    sys.exit(1)

def generateFont(path, size, name="customFont"):
    code = []

    try:
        font = ImageFont.truetype(path, size)
    except IOError:
        print(f"Error: Could not load font '{path}'.")
        sys.exit(1)

    # Get vertical metrics to maintain a consistent baseline
    ascent, descent = font.getmetrics()
    totalH = ascent + descent
    
    # Calculate how many 8-pixel pages this font requires
    hPages = math.ceil(totalH / 8.0)
    code.append(f"// hPages={hPages}")
    
    chars = [chr(i) for i in range(32, 127)]
    
    glyphs = []
    bits = []
    currentOffset = 0
    
    for c in chars:
        # Get advance width for proportional spacing
        advance = int(math.ceil(font.getlength(c)))
        if advance == 0:
            advance = int(size / 3) # Fallback for empty/space characters

        bbox = font.getbbox(c, anchor="la")

        if bbox is None:
            inkW = 0
            left = 0
        else:
            left, top, right, bottom = bbox
            inkW = max(0, right - left)

        # Only generate bits if the character actually has ink
        if inkW > 0:
            # Create a 1-bit canvas exactly the width of the ink
            img = Image.new('1', (inkW, totalH), color=0)
            draw = ImageDraw.Draw(img)
            
            # Draw at X = -left to strip away the Left Side Bearing padding
            draw.text((-left, 0), c, font=font, fill=1, anchor="la")
            pixels = img.load()
            
            # Convert to MONO_VTILED: Page by Page, Column by Column
            for p in range(hPages):
                for x in range(inkW):
                    byte = 0
                    for bit in range(8):
                        y = p * 8 + bit
                        if y < totalH and pixels[x, y] > 0:
                            byte |= (1 << bit)
                    bits.append(byte)
                
        glyphs.append({
            'char': c,
            'offset': currentOffset,
            'inkW': inkW,
            'advance': advance
        })
        currentOffset += (inkW * hPages)

    # --- Generate C++ Code ---
    code.append("/* Automatically generated by ttf-to-cxx.py */")
    code.append("#include <FrameBuffer.h>\n")

    code.append(f"extern const FrameBuffer::Font {name}({hPages}, {{")
    for g in glyphs:
        ch = g['char'].replace('\\', '\\\\').replace("'", "\\'")
        code.append(f"    {{ {g['offset']:5d}, {g['inkW']:3d}, {g['advance']:3d} }}, // '{ch}'")
    code.append("  }, {")
    for i in range(0, len(bits), 12):
        chunk = bits[i:i+12]
        hex = ", ".join([f"0x{b:02X}" for b in chunk])
        code.append(f"    {hex},")
    code.append("});\n")

    return "\n".join(code)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Convert TTF to MONO_VTILED C struct.")
    parser.add_argument("path", help="Path to TTF/OTF font file")
    parser.add_argument("size", type=int, help="Font size in pixels")
    parser.add_argument("--name", default="customFont", help="Name of the generated C variable")
    args = parser.parse_args()

    source = generateFont(args.path, args.size, args.name)
    print(source)
