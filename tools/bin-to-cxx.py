#!/usr/bin/env python3
import sys
import argparse

def main():
  parser = argparse.ArgumentParser(description="Convert a binary file into a C++ source file.")
  parser.add_argument("inputFile", help="Path to input binary file")
  parser.add_argument("--name", default="binaryData", help="Variable name for the byte array")
  parser.add_argument("--namespace", default="", help="Optional C++ namespace")
  parser.add_argument("--output", default="-", help="Output file path (default: stdout)")
  args = parser.parse_args()

  try:
    with open(args.inputFile, "rb") as f:
      data = f.read()
  except IOError as err:
    sys.stderr.write(f"Error reading '{args.inputFile}': {err}\n")
    sys.exit(1)

  outLines = []
  outLines.append("// Generated by bin-to-cxx.py - DO NOT EDIT")
  outLines.append("#include <stddef.h>")
  outLines.append("#include <stdint.h>")
  outLines.append("")

  if args.namespace:
    outLines.append(f"namespace {args.namespace} {{")
    outLines.append("")

  outLines.append(f"alignas(4) extern const uint8_t {args.name}[] = {{")

  bytesPerLine = 12
  for i in range(0, len(data), bytesPerLine):
    chunk = data[i:i + bytesPerLine]
    hexStr = ", ".join(f"0x{b:02X}" for b in chunk)
    if i + bytesPerLine < len(data):
      outLines.append(f"  {hexStr},")
    else:
      outLines.append(f"  {hexStr}")

  outLines.append("};")
  outLines.append("")
  outLines.append(f"extern const size_t {args.name}Len = sizeof({args.name});")
  outLines.append("")

  if args.namespace:
    outLines.append(f"}} // namespace {args.namespace}")
    outLines.append("")

  outContent = "\n".join(outLines)

  if args.output == "-" or not args.output:
    sys.stdout.write(outContent)
  else:
    try:
      with open(args.output, "w") as f:
        f.write(outContent)
    except IOError as err:
      sys.stderr.write(f"Error writing to '{args.output}': {err}\n")
      sys.exit(1)

if __name__ == "__main__":
  main()
